/**
 * SQL the sidebar menus and the table designer write, in each database's own
 * syntax. Statements carry no terminator: they run one by one through
 * `execute`, and {@link toScript} adds what the editor's splitter expects.
 *
 * `ddl.fixtures.test.ts` keeps the statements for a fixed set of cases in
 * `ddl.fixtures.json`, which the Rust integration tests run against every
 * database (`src-tauri/src/drivers/ddl_fixtures.rs`).
 */
import type { Engine, InferredType } from "../api";
import { qualified, quoteIdent, redisArg } from "./ident";

/** A column in the table designer. */
export interface ColumnSpec {
	name: string;
	type: string;
	nullable: boolean;
	/** SQL expression; empty for none. */
	defaultValue: string;
	primaryKey: boolean;
	/** Values generated by the database (identity, AUTO_INCREMENT...); new columns only. */
	identity: boolean;
}

/** A designer row: `origin` is the column it edits, null for a new one. */
export interface ColumnDraft extends ColumnSpec {
	origin: string | null;
}

export interface SqlPlan {
	statements: string[];
	/** What the database cannot do this way, or what the statements lose. */
	warnings: string[];
}

const isMysql = (e: Engine) => e === "mysql" || e === "mariadb";

/**
 * A name typed for a new object, folded the way the database folds unquoted
 * names (lowercase in PostgreSQL, uppercase in Oracle) so it needs no quotes.
 * Names with other characters keep their case and get quoted.
 */
export function foldName(name: string, engine: Engine): string {
	const n = name.trim();
	if (!/^[A-Za-z_][A-Za-z0-9_$#]*$/.test(n)) return n;
	if (engine === "postgres") return n.toLowerCase();
	if (engine === "oracle") return n.toUpperCase();
	return n;
}

/** Function names in the tree carry their argument types: `f(integer, text)`. */
function splitArgs(name: string): { base: string; args: string } {
	const i = name.indexOf("(");
	return i > 0 && name.endsWith(")") ? { base: name.slice(0, i), args: name.slice(i) } : { base: name, args: "" };
}

const target = (schema: string, name: string, engine: Engine) => qualified(schema, name, engine);

/** T-SQL string literal. */
const nstr = (s: string) => `N'${s.replace(/'/g, "''")}'`;

/** Plain SQL string literal. */
export const literal = (s: string) => `'${s.replace(/'/g, "''")}'`;

// ---- columns -------------------------------------------------------------

function identityClause(engine: Engine): string {
	switch (engine) {
		case "postgres":
		case "oracle":
			return "GENERATED BY DEFAULT AS IDENTITY";
		case "mysql":
		case "mariadb":
			return "AUTO_INCREMENT";
		case "sqlserver":
			return "IDENTITY(1,1)";
		default:
			return "";
	}
}

/** Column definition for CREATE TABLE and ADD COLUMN. */
export function columnDef(c: ColumnSpec, engine: Engine, inlinePk = false): string {
	const parts = [quoteIdent(c.name, engine), c.type.trim()];
	const def = c.defaultValue.trim();
	const notNull = !c.nullable || c.primaryKey;
	switch (engine) {
		case "postgres":
		case "oracle":
			if (c.identity) parts.push(identityClause(engine));
			else if (def) parts.push(`DEFAULT ${def}`);
			if (notNull) parts.push("NOT NULL");
			break;
		case "mysql":
		case "mariadb":
			if (notNull) parts.push("NOT NULL");
			if (def && !c.identity) parts.push(`DEFAULT ${def}`);
			if (c.identity) parts.push(identityClause(engine));
			break;
		case "sqlserver":
			if (c.identity) parts.push(identityClause(engine));
			parts.push(notNull ? "NOT NULL" : "NULL");
			if (def && !c.identity) parts.push(`DEFAULT ${def}`);
			break;
		case "sqlite":
			if (inlinePk) {
				parts.push(c.identity ? "PRIMARY KEY AUTOINCREMENT" : "PRIMARY KEY");
				break;
			}
			if (notNull) parts.push("NOT NULL");
			if (def) parts.push(`DEFAULT ${def}`);
			break;
		case "redis":
			break;
	}
	return parts.join(" ");
}

function checkColumns(columns: ColumnSpec[], warnings: string[]): boolean {
	const names = new Set<string>();
	let ok = true;
	for (const c of columns) {
		if (!c.name.trim()) {
			warnings.push("Every column needs a name.");
			ok = false;
		} else if (!c.type.trim()) {
			warnings.push(`Column ${c.name} needs a type.`);
			ok = false;
		}
		const key = c.name.trim().toLowerCase();
		if (key && names.has(key)) {
			warnings.push(`Column ${c.name} appears twice.`);
			ok = false;
		}
		names.add(key);
	}
	return ok;
}

// ---- create and alter tables ----------------------------------------------

export function createTableSql(schema: string, name: string, columns: ColumnSpec[], engine: Engine): SqlPlan {
	const warnings: string[] = [];
	if (!name.trim()) warnings.push("The table needs a name.");
	if (columns.length === 0) warnings.push("Add at least one column.");
	if (!checkColumns(columns, warnings) || !name.trim() || columns.length === 0) {
		return { statements: [], warnings };
	}
	const pk = columns.filter((c) => c.primaryKey);
	const identities = columns.filter((c) => c.identity);
	// SQLite generates values only for an INTEGER PRIMARY KEY column.
	const sqliteRowid =
		engine === "sqlite" && pk.length === 1 && /^integer$/i.test(pk[0].type.trim()) ? pk[0] : null;
	if (engine === "sqlite" && identities.some((c) => c !== sqliteRowid)) {
		warnings.push("SQLite generates values only for a single INTEGER PRIMARY KEY column.");
	}
	if (isMysql(engine) && identities.some((c) => !c.primaryKey)) {
		warnings.push("AUTO_INCREMENT needs the column to be the primary key (or the first column of an index).");
	}
	if (identities.length > 1 && engine !== "postgres" && engine !== "oracle") {
		warnings.push("Only one column per table can generate values.");
	}
	const lines = columns.map((c) => `    ${columnDef(c, engine, c === sqliteRowid)}`);
	if (pk.length > 0 && !sqliteRowid) {
		lines.push(`    PRIMARY KEY (${pk.map((c) => quoteIdent(c.name, engine)).join(", ")})`);
	}
	return {
		statements: [`CREATE TABLE ${target(schema, name, engine)} (\n${lines.join(",\n")}\n)`],
		warnings,
	};
}

/** Statements that drop a SQL Server column's default constraint, whatever its name. */
function mssqlDropDefault(table: string, column: string): string {
	return [
		"BEGIN",
		`    DECLARE @lq_sql nvarchar(max) = (SELECT N'ALTER TABLE ${table.replace(/'/g, "''")} DROP CONSTRAINT ' + QUOTENAME(dc.name)`,
		"        FROM sys.default_constraints dc",
		"        JOIN sys.columns c ON c.object_id = dc.parent_object_id AND c.column_id = dc.parent_column_id",
		`        WHERE dc.parent_object_id = OBJECT_ID(${nstr(table)}) AND c.name = ${nstr(column)});`,
		"    IF @lq_sql IS NOT NULL EXEC (@lq_sql);",
		"END",
	].join("\n");
}

/**
 * ALTER statements that turn the `before` columns into the designer rows,
 * then rename the table when `newName` differs.
 */
export function alterTableSql(
	schema: string,
	table: string,
	before: ColumnSpec[],
	after: ColumnDraft[],
	engine: Engine,
	newName = table,
): SqlPlan {
	const warnings: string[] = [];
	if (!checkColumns(after, warnings)) return { statements: [], warnings };
	const t = target(schema, table, engine);
	const q = (n: string) => quoteIdent(n, engine);
	const out: string[] = [];
	const unsupported = (what: string) => warnings.push(`SQLite cannot ${what}; recreate the table to do it.`);

	const kept = new Set(after.filter((c) => c.origin !== null).map((c) => c.origin));
	for (const old of before) {
		if (kept.has(old.name)) continue;
		if (engine === "sqlserver" && old.defaultValue) out.push(mssqlDropDefault(t, old.name));
		out.push(`ALTER TABLE ${t} DROP COLUMN ${q(old.name)}`);
	}

	for (const c of after) {
		if (c.origin === null) continue;
		const old = before.find((b) => b.name === c.origin);
		if (!old) continue;
		let name = old.name;
		if (c.name.trim() !== old.name) {
			const renamed = c.name.trim();
			out.push(
				engine === "sqlserver"
					? `EXEC sp_rename ${nstr(`${t}.${q(old.name)}`)}, ${nstr(renamed)}, N'COLUMN'`
					: `ALTER TABLE ${t} RENAME COLUMN ${q(old.name)} TO ${q(renamed)}`,
			);
			name = renamed;
		}
		const col = q(name);
		const typeChanged = c.type.trim() !== old.type.trim();
		const nullChanged = c.nullable !== old.nullable && !c.primaryKey;
		const def = c.defaultValue.trim();
		const defaultChanged = def !== (old.defaultValue ?? "").trim();
		if (!typeChanged && !nullChanged && !defaultChanged) continue;
		switch (engine) {
			case "postgres":
				if (typeChanged) out.push(`ALTER TABLE ${t} ALTER COLUMN ${col} TYPE ${c.type.trim()}`);
				if (nullChanged) out.push(`ALTER TABLE ${t} ALTER COLUMN ${col} ${c.nullable ? "DROP" : "SET"} NOT NULL`);
				if (defaultChanged) {
					out.push(def ? `ALTER TABLE ${t} ALTER COLUMN ${col} SET DEFAULT ${def}` : `ALTER TABLE ${t} ALTER COLUMN ${col} DROP DEFAULT`);
				}
				break;
			case "oracle": {
				const parts = [col];
				if (typeChanged) parts.push(c.type.trim());
				if (defaultChanged) parts.push(`DEFAULT ${def || "NULL"}`);
				if (nullChanged) parts.push(c.nullable ? "NULL" : "NOT NULL");
				out.push(`ALTER TABLE ${t} MODIFY (${parts.join(" ")})`);
				break;
			}
			case "mysql":
			case "mariadb":
				if (typeChanged || nullChanged) {
					out.push(`ALTER TABLE ${t} MODIFY COLUMN ${columnDef({ ...c, name, identity: false }, engine)}`);
					warnings.push(
						`MODIFY COLUMN rewrites ${name}: AUTO_INCREMENT, comments and character sets it had are not kept unless you add them to the statement.`,
					);
				} else {
					out.push(def ? `ALTER TABLE ${t} ALTER COLUMN ${col} SET DEFAULT ${def}` : `ALTER TABLE ${t} ALTER COLUMN ${col} DROP DEFAULT`);
				}
				break;
			case "sqlserver": {
				const hadDefault = !!(old.defaultValue ?? "").trim();
				if (hadDefault && (defaultChanged || typeChanged)) out.push(mssqlDropDefault(t, name));
				if (typeChanged || nullChanged) {
					out.push(`ALTER TABLE ${t} ALTER COLUMN ${col} ${c.type.trim()} ${c.nullable ? "NULL" : "NOT NULL"}`);
				}
				if (def && (defaultChanged || (hadDefault && typeChanged))) out.push(`ALTER TABLE ${t} ADD DEFAULT ${def} FOR ${col}`);
				break;
			}
			case "sqlite":
				if (typeChanged) unsupported(`change the type of ${name}`);
				if (nullChanged) unsupported(`change whether ${name} accepts NULL`);
				if (defaultChanged) unsupported(`change the default of ${name}`);
				break;
			case "redis":
				break;
		}
	}

	for (const c of after) {
		if (c.origin !== null) continue;
		if (engine === "sqlite" && !c.nullable && !c.defaultValue.trim()) {
			warnings.push(`SQLite adds a NOT NULL column only with a default; give ${c.name} one.`);
		}
		if (engine === "sqlite" && (c.primaryKey || c.identity)) unsupported(`add a primary key column (${c.name})`);
		const spec = { ...c, primaryKey: false };
		const def = columnDef({ ...spec, nullable: c.nullable && !c.primaryKey }, engine);
		out.push(
			engine === "oracle"
				? `ALTER TABLE ${t} ADD (${def})`
				: engine === "sqlserver"
					? `ALTER TABLE ${t} ADD ${def}`
					: `ALTER TABLE ${t} ADD COLUMN ${def}`,
		);
	}

	const pkBefore = before.filter((c) => c.primaryKey).map((c) => c.name);
	const pkAfter = after.filter((c) => c.primaryKey);
	const afterNames = pkAfter.map((c) => (c.origin ?? "") + "\u0000" + c.name.trim());
	const beforeNames = pkBefore.map((n) => n + "\u0000" + (after.find((c) => c.origin === n)?.name.trim() ?? ""));
	if (afterNames.join("|") !== beforeNames.join("|")) {
		const cols = pkAfter.map((c) => q(c.name.trim())).join(", ");
		if (engine === "sqlite") {
			unsupported("change the primary key");
		} else if (pkBefore.length === 0) {
			out.push(`ALTER TABLE ${t} ADD PRIMARY KEY (${cols})`);
		} else if (isMysql(engine) || engine === "oracle") {
			out.push(`ALTER TABLE ${t} DROP PRIMARY KEY`);
			if (cols) out.push(`ALTER TABLE ${t} ADD PRIMARY KEY (${cols})`);
		} else {
			warnings.push(
				"The primary key changed: drop the existing primary key constraint (its name is in the table's DDL) before adding the new one.",
			);
			if (cols) out.push(`ALTER TABLE ${t} ADD PRIMARY KEY (${cols})`);
		}
	}

	const renamed = newName.trim();
	if (renamed && renamed !== table) out.push(...renameTableSql(schema, table, renamed, engine));
	if (out.length === 0 && warnings.length === 0) warnings.push("Nothing changed.");
	return { statements: out, warnings };
}

// ---- table and object actions ----------------------------------------------

export function renameTableSql(schema: string, table: string, newName: string, engine: Engine): string[] {
	const t = target(schema, table, engine);
	switch (engine) {
		case "mysql":
		case "mariadb":
			return [`RENAME TABLE ${t} TO ${target(schema, newName, engine)}`];
		case "sqlserver":
			return [`EXEC sp_rename ${nstr(t)}, ${nstr(newName)}`];
		default:
			return [`ALTER TABLE ${t} RENAME TO ${quoteIdent(newName, engine)}`];
	}
}

/** A copy of the table, empty or with its rows. */
export function duplicateTableSql(schema: string, table: string, newName: string, withData: boolean, engine: Engine): SqlPlan {
	const from = target(schema, table, engine);
	const to = target(schema, newName, engine);
	switch (engine) {
		case "postgres":
			return {
				statements: [
					`CREATE TABLE ${to} (LIKE ${from} INCLUDING ALL)`,
					...(withData ? [`INSERT INTO ${to} OVERRIDING SYSTEM VALUE SELECT * FROM ${from}`] : []),
				],
				warnings: ["Foreign keys and triggers are not copied."],
			};
		case "mysql":
		case "mariadb":
			return {
				statements: [`CREATE TABLE ${to} LIKE ${from}`, ...(withData ? [`INSERT INTO ${to} SELECT * FROM ${from}`] : [])],
				warnings: ["Foreign keys and triggers are not copied."],
			};
		case "oracle":
			return {
				statements: [`CREATE TABLE ${to} AS SELECT * FROM ${from}${withData ? "" : " WHERE 1 = 0"}`],
				warnings: ["Only columns, types and NOT NULL are copied: add keys, indexes and defaults to the copy."],
			};
		case "sqlserver":
			return {
				statements: [`SELECT * INTO ${to} FROM ${from}${withData ? "" : " WHERE 1 = 0"}`],
				warnings: ["Only columns, types, NULL and identity are copied: add keys, indexes and defaults to the copy."],
			};
		case "sqlite":
			return {
				statements: [`CREATE TABLE ${to} AS SELECT * FROM ${from}${withData ? "" : " WHERE 0"}`],
				warnings: ["Only columns are copied: keys, constraints and defaults are not."],
			};
		case "redis":
			return { statements: [], warnings: [] };
	}
}

export function truncateSql(schema: string, table: string, engine: Engine): string[] {
	const t = target(schema, table, engine);
	return [engine === "sqlite" ? `DELETE FROM ${t}` : `TRUNCATE TABLE ${t}`];
}

/** Kinds with a DROP statement (and a cascade option where `cascade` is set). */
export function canDrop(kind: string, engine: Engine): boolean {
	if (engine === "redis") return false;
	if (engine === "sqlite") return kind === "table" || kind === "view";
	return ["table", "view", "matview", "foreign", "sequence", "function", "procedure", "package", "type", "synonym"].includes(kind);
}

/** Whether DROP of this kind can also drop what depends on it. */
export function dropCascades(kind: string, engine: Engine): boolean {
	if (engine === "postgres") return kind !== "package" && kind !== "synonym";
	if (engine === "oracle") return kind === "table" || kind === "type";
	return false;
}

export function dropObjectSql(schema: string, name: string, kind: string, engine: Engine, cascade = false): string[] {
	const { base, args } = splitArgs(name);
	const t = engine === "postgres" ? `${target(schema, base, engine)}${args}` : target(schema, name, engine);
	const word: Record<string, string> = {
		table: "TABLE",
		view: "VIEW",
		matview: "MATERIALIZED VIEW",
		foreign: "FOREIGN TABLE",
		sequence: "SEQUENCE",
		function: "FUNCTION",
		procedure: "PROCEDURE",
		package: "PACKAGE",
		type: "TYPE",
		synonym: "SYNONYM",
	};
	if (engine === "oracle" && kind === "synonym" && schema === "PUBLIC") {
		return [`DROP PUBLIC SYNONYM ${quoteIdent(name, engine)}`];
	}
	let sql = `DROP ${word[kind] ?? kind.toUpperCase()} ${t}`;
	if (cascade && dropCascades(kind, engine)) {
		sql += engine === "oracle" ? (kind === "table" ? " CASCADE CONSTRAINTS" : " FORCE") : " CASCADE";
	}
	return [sql];
}

export function refreshMatviewSql(schema: string, name: string, engine: Engine): string[] {
	if (engine === "oracle") {
		return [`BEGIN\n    DBMS_MVIEW.REFRESH(${literal(`${quoteIdent(schema, engine)}.${quoteIdent(name, engine)}`)});\nEND;`];
	}
	return [`REFRESH MATERIALIZED VIEW ${target(schema, name, engine)}`];
}

// ---- schemas and databases --------------------------------------------------

/** What the second level of the tree is called for this engine. */
export function schemaWord(engine: Engine): string {
	return isMysql(engine) || engine === "redis" || engine === "sqlite" ? "database" : "schema";
}

export function createSchemaSql(name: string, engine: Engine): string[] {
	const n = quoteIdent(name, engine);
	return [isMysql(engine) ? `CREATE DATABASE ${n}` : `CREATE SCHEMA ${n}`];
}

export function createDatabaseSql(name: string, engine: Engine): string[] {
	return [`CREATE DATABASE ${quoteIdent(name, engine)}`];
}

export function renameSchemaSql(name: string, newName: string, engine: Engine): string[] {
	return engine === "postgres" ? [`ALTER SCHEMA ${quoteIdent(name, engine)} RENAME TO ${quoteIdent(newName, engine)}`] : [];
}

export function dropSchemaSql(name: string, engine: Engine, cascade = false): string[] {
	const n = quoteIdent(name, engine);
	switch (engine) {
		case "postgres":
			return [`DROP SCHEMA ${n}${cascade ? " CASCADE" : ""}`];
		case "mysql":
		case "mariadb":
			return [`DROP DATABASE ${n}`];
		case "oracle":
			return [`DROP USER ${n}${cascade ? " CASCADE" : ""}`];
		case "sqlserver":
			return [`DROP SCHEMA ${n}`];
		case "sqlite":
			return [`DETACH DATABASE ${n}`];
		case "redis":
			return ["FLUSHDB"];
	}
}

/** Statement that makes a new tab's session work in this schema, if any. */
export function useSchemaSql(name: string, engine: Engine): string | null {
	const n = quoteIdent(name, engine);
	switch (engine) {
		case "postgres":
			return `SET search_path TO ${n}`;
		case "mysql":
		case "mariadb":
			return `USE ${n}`;
		case "oracle":
			return `ALTER SESSION SET CURRENT_SCHEMA = ${n}`;
		case "redis":
			return `SELECT ${name.replace(/^db/, "")}`;
		default:
			return null;
	}
}

/** Sessions connected to the server, for the connection menu. */
export function sessionsSql(engine: Engine): string | null {
	switch (engine) {
		case "postgres":
			return "SELECT pid, usename, datname, application_name, client_addr, state, backend_start,\n       query_start, wait_event_type, wait_event, query\nFROM pg_stat_activity\nORDER BY backend_start";
		case "mysql":
		case "mariadb":
			return "SHOW FULL PROCESSLIST";
		case "oracle":
			return "SELECT sid, serial#, username, status, osuser, machine, program, logon_time, sql_id, event\nFROM v$session\nWHERE type = 'USER'\nORDER BY logon_time";
		case "sqlserver":
			return "SELECT s.session_id, s.login_name, s.host_name, s.program_name, s.status, s.login_time,\n       DB_NAME(s.database_id) AS database_name, r.command, r.wait_type, r.blocking_session_id\nFROM sys.dm_exec_sessions s\nLEFT JOIN sys.dm_exec_requests r ON r.session_id = s.session_id\nWHERE s.is_user_process = 1\nORDER BY s.login_time";
		case "redis":
			return "CLIENT LIST";
		default:
			return null;
	}
}

// ---- generated statements ------------------------------------------------------

export function countSql(schema: string, table: string, engine: Engine): string {
	return `SELECT COUNT(*) FROM ${target(schema, table, engine)}`;
}

export function selectSql(schema: string, table: string, columns: string[], engine: Engine): string {
	const cols = columns.length ? columns.map((c) => quoteIdent(c, engine)).join(",\n       ") : "*";
	return `SELECT ${cols}\nFROM ${target(schema, table, engine)}`;
}

export function insertSql(schema: string, table: string, columns: string[], engine: Engine): string {
	const cols = columns.map((c) => quoteIdent(c, engine));
	return `INSERT INTO ${target(schema, table, engine)} (${cols.join(", ")})\nVALUES (${cols.map(() => "?").join(", ")})`;
}

export function updateSql(schema: string, table: string, columns: string[], key: string[], engine: Engine): string {
	const keys = key.length ? key : columns.slice(0, 1);
	const set = columns.filter((c) => !keys.includes(c));
	const assign = (set.length ? set : columns).map((c) => `${quoteIdent(c, engine)} = ?`).join(",\n    ");
	const where = keys.map((c) => `${quoteIdent(c, engine)} = ?`).join("\n  AND ");
	return `UPDATE ${target(schema, table, engine)}\nSET ${assign}\nWHERE ${where}`;
}

export function deleteSql(schema: string, table: string, columns: string[], key: string[], engine: Engine): string {
	const keys = key.length ? key : columns.slice(0, 1);
	const where = keys.map((c) => `${quoteIdent(c, engine)} = ?`).join("\n  AND ");
	return `DELETE FROM ${target(schema, table, engine)}\nWHERE ${where}`;
}

export function createIndexSql(schema: string, table: string, column: string, engine: Engine): string {
	const name = foldName(`ix_${table}_${column}`.replace(/[^A-Za-z0-9_]/g, "_").slice(0, 60), engine);
	// SQLite qualifies the index, never the table; Oracle may qualify both;
	// the others keep the index in the table's schema.
	const on = engine === "sqlite" ? quoteIdent(table, engine) : target(schema, table, engine);
	const ix = engine === "sqlite" || engine === "oracle" ? target(schema, name, engine) : quoteIdent(name, engine);
	return `CREATE INDEX ${ix} ON ${on} (${quoteIdent(column, engine)})`;
}

/** Skeletons for new objects, opened in the editor. */
export function objectTemplate(kind: "view" | "function" | "procedure" | "sequence", schema: string, engine: Engine): string {
	const name = (n: string) => target(schema, foldName(n, engine), engine);
	switch (kind) {
		case "view":
			return `CREATE VIEW ${name("new_view")} AS\nSELECT *\nFROM ${name("table_name")}`;
		case "sequence":
			return `CREATE SEQUENCE ${name("new_sequence")}\n    START WITH 1\n    INCREMENT BY 1`;
		case "function":
			switch (engine) {
				case "postgres":
					return `CREATE OR REPLACE FUNCTION ${name("new_function")}(p_value integer)\nRETURNS integer\nLANGUAGE sql\nAS $$\n    SELECT p_value * 2\n$$`;
				case "oracle":
					return `CREATE OR REPLACE FUNCTION ${name("new_function")}(p_value IN NUMBER)\nRETURN NUMBER\nIS\nBEGIN\n    RETURN p_value * 2;\nEND;\n/`;
				case "sqlserver":
					return `CREATE FUNCTION ${name("new_function")}(@value int)\nRETURNS int\nAS\nBEGIN\n    RETURN @value * 2;\nEND\nGO`;
				default:
					return `DELIMITER $$\nCREATE FUNCTION ${name("new_function")}(p_value INT)\nRETURNS INT\nDETERMINISTIC\nBEGIN\n    RETURN p_value * 2;\nEND$$\nDELIMITER ;`;
			}
		case "procedure":
			switch (engine) {
				case "postgres":
					return `CREATE OR REPLACE PROCEDURE ${name("new_procedure")}(p_value integer)\nLANGUAGE plpgsql\nAS $$\nBEGIN\n    RAISE NOTICE 'value: %', p_value;\nEND;\n$$`;
				case "oracle":
					return `CREATE OR REPLACE PROCEDURE ${name("new_procedure")}(p_value IN NUMBER)\nIS\nBEGIN\n    DBMS_OUTPUT.PUT_LINE('value: ' || p_value);\nEND;\n/`;
				case "sqlserver":
					return `CREATE PROCEDURE ${name("new_procedure")}\n    @value int\nAS\nBEGIN\n    SET NOCOUNT ON;\n    SELECT @value AS value;\nEND\nGO`;
				default:
					return `DELIMITER $$\nCREATE PROCEDURE ${name("new_procedure")}(IN p_value INT)\nBEGIN\n    SELECT p_value;\nEND$$\nDELIMITER ;`;
			}
	}
}

/** Oracle: creating a schema means creating a user. */
export function oracleUserTemplate(): string {
	return 'CREATE USER new_schema IDENTIFIED BY "change_me";\nGRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE TO new_schema;\nALTER USER new_schema QUOTA UNLIMITED ON USERS;';
}

/** Kinds whose DDL the driver can read (`object_ddl`). */
export function hasDdl(kind: string, engine: Engine): boolean {
	switch (engine) {
		case "postgres":
			return ["table", "view", "matview", "foreign", "sequence", "function", "procedure"].includes(kind);
		case "oracle":
			return ["table", "view", "matview", "sequence", "function", "procedure", "package", "type", "synonym"].includes(kind);
		case "mysql":
		case "mariadb":
			return ["table", "view", "sequence", "function", "procedure"].includes(kind);
		case "sqlserver":
			return ["table", "view", "sequence", "function", "procedure", "synonym", "type"].includes(kind);
		case "sqlite":
			return kind === "table" || kind === "view";
		case "redis":
			return false;
	}
}

/** Object templates the schema menu offers. */
export function templateKinds(engine: Engine): ("view" | "function" | "procedure" | "sequence")[] {
	switch (engine) {
		case "postgres":
		case "oracle":
		case "sqlserver":
		case "mariadb":
			return ["view", "function", "procedure", "sequence"];
		case "mysql":
			return ["view", "function", "procedure"];
		case "sqlite":
			return ["view"];
		case "redis":
			return [];
	}
}

type FixedKind = Exclude<InferredType, "text">;

/** Column types for values found in an imported file, per engine. */
const IMPORT_TYPES: Record<FixedKind, Record<Engine, string>> = {
	integer: { postgres: "bigint", oracle: "NUMBER(19)", mysql: "BIGINT", mariadb: "BIGINT", sqlserver: "bigint", sqlite: "INTEGER", redis: "" },
	decimal: { postgres: "numeric", oracle: "NUMBER", mysql: "DECIMAL(28,8)", mariadb: "DECIMAL(28,8)", sqlserver: "decimal(28,8)", sqlite: "NUMERIC", redis: "" },
	boolean: { postgres: "boolean", oracle: "NUMBER(1)", mysql: "TINYINT(1)", mariadb: "TINYINT(1)", sqlserver: "bit", sqlite: "INTEGER", redis: "" },
	date: { postgres: "date", oracle: "DATE", mysql: "DATE", mariadb: "DATE", sqlserver: "date", sqlite: "TEXT", redis: "" },
	timestamp: { postgres: "timestamp", oracle: "TIMESTAMP", mysql: "DATETIME(6)", mariadb: "DATETIME(6)", sqlserver: "datetime2", sqlite: "TEXT", redis: "" },
};

/** Column type for a kind of value found in an imported file; text gets room to grow. */
export function typeFor(kind: InferredType, maxLength: number, engine: Engine): string {
	if (kind !== "text") return IMPORT_TYPES[kind][engine];
	const len = Math.max(50, Math.ceil((maxLength * 1.5) / 10) * 10);
	switch (engine) {
		case "postgres":
			return "text";
		case "sqlite":
			return "TEXT";
		case "oracle":
			return len <= 4000 ? `VARCHAR2(${len} CHAR)` : "CLOB";
		case "sqlserver":
			return len <= 4000 ? `nvarchar(${len})` : "nvarchar(max)";
		default:
			return len <= 4000 ? `VARCHAR(${len})` : "LONGTEXT";
	}
}

// ---- Redis keys ---------------------------------------------------------------

export function redisKeySql(action: "delete" | "rename" | "expire" | "persist", key: string, value = ""): string {
	const k = redisArg(key);
	switch (action) {
		case "delete":
			return `DEL ${k}`;
		case "rename":
			return `RENAME ${k} ${redisArg(value)}`;
		case "expire":
			return `EXPIRE ${k} ${value}`;
		case "persist":
			return `PERSIST ${k}`;
	}
}

// ---- scripts ----------------------------------------------------------------------

/** Statements as an editor script, terminated the way the editor splits them. */
export function toScript(statements: string[], engine: Engine): string {
	if (engine === "redis") return statements.join("\n");
	return statements
		.map((s) => {
			if (engine === "oracle" && /^(BEGIN|DECLARE)\b/i.test(s)) return `${s}\n/`;
			return `${s};`;
		})
		.join("\n\n");
}
